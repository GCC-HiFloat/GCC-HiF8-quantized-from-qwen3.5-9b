"""Generate device-side tables from the reference format definition."""

from __future__ import annotations

import argparse
import math
import struct
from pathlib import Path

from .codec import ASCEND_DECODE_TABLE
from .torch_codec import FLOAT32_ENCODE_LUT


def _float_literal(value: float) -> str:
    # Builtins rather than <math.h> macros: the header is included by AscendC
    # kernel sources, which do not pull in the host math headers.
    if math.isnan(value):
        return '__builtin_nanf("")'
    if math.isinf(value):
        return "-__builtin_inff()" if value < 0.0 else "__builtin_inff()"
    return f"{value.hex()}f"


def _signed_encode_lut() -> tuple[int, ...]:
    """Encode from FP32 sign/exponent/top-mantissa bits directly."""
    output: list[int] = []
    for index in range(8192):
        sign = 0x80 if index & 0x1000 else 0
        magnitude_index = index & 0x0FFF
        exponent = magnitude_index >> 4
        mantissa_top = magnitude_index & 0x0F
        if exponent == 0xFF:
            output.append(0x80 if mantissa_top else 0x6F | sign)
            continue
        magnitude = FLOAT32_ENCODE_LUT[magnitude_index]
        output.append(magnitude if magnitude == 0 else magnitude | sign)
    return tuple(output)


def _static_signed_encode_lut() -> tuple[int, ...]:
    """Encode FP32 with finite overflow saturated instead of made infinite."""
    output: list[int] = []
    for index, payload in enumerate(_signed_encode_lut()):
        magnitude_index = index & 0x0FFF
        exponent = magnitude_index >> 4
        if exponent != 0xFF and (payload & 0x7F) == 0x6F:
            payload = (payload & 0x80) | 0x6E
        output.append(payload)
    return tuple(output)


def _pack_u8x4(values: tuple[int, ...]) -> tuple[int, ...]:
    return tuple(
        values[offset] | (values[offset + 1] << 8) | (values[offset + 2] << 16) | (values[offset + 3] << 24)
        for offset in range(0, len(values), 4)
    )


def _pack_u16x2(values: tuple[int, ...]) -> tuple[int, ...]:
    return tuple(values[offset] | (values[offset + 1] << 16) for offset in range(0, len(values), 2))


def _float_to_bf16_bits(value: float) -> int:
    """Return the Ascend BF16 bit pattern for an FP32 value.

    The device-side fused activation path uses a table of BF16 bit patterns
    rather than a second U8 encode/decode gather.  All finite HiFloat8 decode
    values are exactly representable in BF16; for NaN use the canonical quiet
    payload consumed by ``DecodeBf16``.
    """
    if math.isnan(value):
        return 0x7FC0
    bits = struct.unpack("!I", struct.pack("!f", value))[0]
    return bits >> 16


def _float_to_half_bits(value: float) -> int:
    """Return the canonical IEEE FP16 bit pattern for a Python float."""
    if math.isnan(value):
        return 0x7E00
    return struct.unpack("!H", struct.pack("!e", value))[0]


def _encode_decode_bf16_lut() -> tuple[int, ...]:
    """Build a signed FP32-index -> decoded-HiFloat8 BF16 lookup table."""
    encoded = _signed_encode_lut()
    return tuple(_float_to_bf16_bits(ASCEND_DECODE_TABLE[payload]) for payload in encoded)


def _static_encode_decode_bf16_lut() -> tuple[int, ...]:
    """Build the saturating variant used by fixed-scale quantization.

    Static calibration treats finite overflow as saturation to the largest
    finite HiFloat8 value.  Keep that rule in the fused device path as well;
    otherwise a fixed-scale fused Linear could disagree with the standalone
    ``hif8_static_quant`` operator for an outlier activation.
    """
    encoded = _static_signed_encode_lut()
    return tuple(_float_to_bf16_bits(ASCEND_DECODE_TABLE[payload]) for payload in encoded)


def render_header() -> str:
    positive_decode = ASCEND_DECODE_TABLE[:128]
    decode_bf16_packed = _pack_u16x2(tuple(_float_to_bf16_bits(value) for value in ASCEND_DECODE_TABLE))
    decode_half_packed = _pack_u16x2(tuple(_float_to_half_bits(value) for value in ASCEND_DECODE_TABLE))
    signed_encode_packed = _pack_u16x2(_signed_encode_lut())
    static_signed_encode_packed = _pack_u16x2(_static_signed_encode_lut())
    encode_decode_bf16_packed = _pack_u16x2(_encode_decode_bf16_lut())
    static_encode_decode_bf16_packed = _pack_u16x2(_static_encode_decode_bf16_lut())
    lines = [
        "// Generated by vllm_ascend_hif8.tablegen; do not edit.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "namespace vllm_ascend_hif8 {",
        "constexpr uint8_t kAscendNan = 0x80;",
        "constexpr uint8_t kAscendPositiveInfinity = 0x6f;",
        "constexpr uint8_t kAscendNegativeInfinity = 0xef;",
        "",
        "constexpr float kAscendDecodeMagnitude[128] = {",
    ]
    for offset in range(0, 128, 8):
        values = ", ".join(_float_literal(value) for value in positive_decode[offset : offset + 8])
        lines.append(f"    {values},")
    lines.extend(
        [
            "};",
            "",
            "// Physical HiFloat8 byte -> BF16 payload, two entries per word.",
            "constexpr uint32_t kAscendDecodeBf16U16Packed[128] = {",
        ]
    )
    for offset in range(0, 128, 8):
        values = ", ".join(f"0x{value:08x}u" for value in decode_bf16_packed[offset : offset + 8])
        lines.append(f"    {values},")
    lines.extend(
        [
            "};",
            "",
            "// Physical HiFloat8 byte -> FP16 payload, two entries per word.",
            "constexpr uint32_t kAscendDecodeHalfU16Packed[128] = {",
        ]
    )
    for offset in range(0, 128, 8):
        values = ", ".join(f"0x{value:08x}u" for value in decode_half_packed[offset : offset + 8])
        lines.append(f"    {values},")
    lines.extend(
        [
            "};",
            "",
            "constexpr uint8_t kFloat32EncodeMagnitude[4096] = {",
        ]
    )
    for offset in range(0, 4096, 16):
        values = ", ".join(f"0x{value:02x}" for value in FLOAT32_ENCODE_LUT[offset : offset + 16])
        lines.append(f"    {values},")
    lines.extend(
        [
            "};",
            "",
            "constexpr uint32_t kFloat32EncodeSignedU16Packed[4096] = {",
        ]
    )
    for offset in range(0, 4096, 8):
        values = ", ".join(f"0x{value:08x}u" for value in signed_encode_packed[offset : offset + 8])
        lines.append(f"    {values},")
    lines.extend(
        [
            "};",
            "",
            "// FP32 sign/exponent/top-mantissa -> physical HiFloat8 byte.",
            "// Finite overflow saturates to +/-32768; NaN/Inf stay special.",
            "constexpr uint32_t kFloat32StaticEncodeSignedU16Packed[4096] = {",
        ]
    )
    for offset in range(0, 4096, 8):
        values = ", ".join(f"0x{value:08x}u" for value in static_signed_encode_packed[offset : offset + 8])
        lines.append(f"    {values},")
    lines.extend(
        [
            "};",
            "",
            "// FP32 sign/exponent/top-mantissa index -> decoded HiFloat8 BF16.",
            "// Each uint32 packs two uint16 BF16 payloads.",
            "constexpr uint32_t kFloat32EncodeDecodeBf16U16Packed[4096] = {",
        ]
    )
    for offset in range(0, 4096, 8):
        values = ", ".join(f"0x{value:08x}u" for value in encode_decode_bf16_packed[offset : offset + 8])
        lines.append(f"    {values},")
    lines.extend(
        [
            "};",
            "",
            "// Same lookup with finite overflow saturated to +/-32768.",
            "constexpr uint32_t kFloat32StaticEncodeDecodeBf16U16Packed[4096] = {",
        ]
    )
    for offset in range(0, 4096, 8):
        values = ", ".join(
            f"0x{value:08x}u"
            for value in static_encode_decode_bf16_packed[offset : offset + 8]
        )
        lines.append(f"    {values},")
    lines.extend(["};", "", "}  // namespace vllm_ascend_hif8", ""])
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "output",
        type=Path,
        nargs="?",
        default=Path(__file__).resolve().parents[2] / "csrc" / "opp" / "op_kernel" / "hif8_tables.h",
        help="output C++ header (defaults to the kernel source directory)",
    )
    args = parser.parse_args(argv)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render_header(), encoding="ascii")


if __name__ == "__main__":
    main()
